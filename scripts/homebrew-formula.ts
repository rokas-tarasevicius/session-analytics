#!/usr/bin/env node
/**
 * Render the Homebrew formula for a release: the GitHub Release tarball that npm and the smoke tests installed, run by
 * Homebrew's Node. The release workflow writes the output to rokas-tarasevicius/homebrew-tap; this file is its only source.
 *
 *   node scripts/homebrew-formula.ts --version X.Y.Z --sha256 HEX > session-analytics.rb
 */
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const repository = "rokas-tarasevicius/session-analytics";

/**
 * The formula installs the exact release asset; its test runs no scan of the tester's history, only an empty HOME.
 * It must pass Homebrew's style cops, which the release workflow checks with `brew style` before publishing while the tap is on:
 * lines other than the url stay within 118 columns, and Homebrew's Node is named by `formula_opt_bin`, not `Formula[...]`.
 */
export function homebrewFormula(version: string, sha256: string): string {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`Formula version must be a stable X.Y.Z, not ${JSON.stringify(version)}.`);
  if (!/^[0-9a-f]{64}$/.test(sha256)) throw new Error("Formula sha256 must be 64 lowercase hexadecimal characters.");
  return `# Generated by scripts/homebrew-formula.ts in ${repository} for each release.
# Edits here are overwritten.
class SessionAnalytics < Formula
  desc "Content-free analytics for local coding-agent sessions"
  homepage "https://github.com/${repository}"
  url "https://github.com/${repository}/releases/download/v${version}/session-analytics-${version}.tgz"
  sha256 "${sha256}"
  license "MIT"

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args
    # Pin Homebrew's Node ahead of any older node on PATH; the analysis workers reuse the same runtime.
    env = { PATH: "#{formula_opt_bin("node")}:$PATH" }
    (bin/"session-analytics").write_env_script libexec/"bin/session-analytics", env
  end

  test do
    ENV["HOME"] = testpath
    ENV.keys.grep(/\\A(?:SESSION_ANALYTICS_|CLAUDE_CONFIG_DIR\\z|CODEX_HOME\\z|XDG_)/).each { |key| ENV.delete(key) }
    assert_equal version.to_s, shell_output("#{bin}/session-analytics --version").strip
    assert_match "\\"schemaVersion\\": 1", shell_output("#{bin}/session-analytics report --json --offline --no-index")
  end
end
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [versionFlag, version, shaFlag, sha256, ...rest] = process.argv.slice(2);
    if (versionFlag !== "--version" || shaFlag !== "--sha256" || !version || !sha256 || rest.length) throw new Error("Usage: node scripts/homebrew-formula.ts --version X.Y.Z --sha256 HEX");
    process.stdout.write(homebrewFormula(version, sha256));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : "Formula rendering failed."}\n`);
    process.exitCode = 1;
  }
}
